import type { Recipe } from '../../recipes/recipeService';
import type { UserSettings } from '../../../services/userService';
import type { MealPlan, MealPlanDay, MealPlanMeal } from '../planService';
import { addDays, getStartOfWeek, toLocalDateKey } from '../../../shared/date-utils.ts';

/**
 * Generates a full week of meals based on user settings and available recipes.
 */
export function generateWeekPlan(
    recipes: Recipe[],
    settings: UserSettings | null,
    startDate: Date = new Date(),
    useBatchLunch: boolean = false,
    preferMilkshake: boolean = false
): MealPlan {

    // N1: a plan always starts on its week's Monday, whatever date is passed in.
    const monday = getStartOfWeek(startDate);

    // 1. Defaults if settings are missing
    const dailyTarget = settings?.dailyCalorieTarget || 2000;

    let proteinTarget, carbsTarget, fatTarget;

    if (settings?.macroMode === 'grams' && settings.macroTargets) {
        proteinTarget = settings.macroTargets.protein;
        carbsTarget = settings.macroTargets.carbs;
        fatTarget = settings.macroTargets.fat;
    } else {
        proteinTarget = Math.round((dailyTarget * (settings?.macroSplit?.protein || 30)) / 100 / 4);
        carbsTarget = Math.round((dailyTarget * (settings?.macroSplit?.carbs || 35)) / 100 / 4);
        fatTarget = Math.round((dailyTarget * (settings?.macroSplit?.fat || 35)) / 100 / 9);
    }

    // 2. Filter recipes by type
    let breakfastRecipes = recipes.filter(r => r.mealType === 'breakfast');
    const lunchRecipes = recipes.filter(r => r.mealType === 'lunch');
    const dinnerRecipes = recipes.filter(r => r.mealType === 'dinner');
    const snackRecipes = recipes.filter(r => r.mealType === 'snack');

    // Milkshake Logic
    if (preferMilkshake) {
        const shakeRecipes = breakfastRecipes.filter(r =>
            r.title.toLowerCase().includes('shake') ||
            r.title.toLowerCase().includes('smoothie') ||
            r.tags?.some(t => t.toLowerCase().includes('drink') || t.toLowerCase().includes('liquid'))
        );
        // Only override if we actually have shake recipes
        if (shakeRecipes.length > 0) {
            breakfastRecipes = shakeRecipes;
        }
    }

    // Fallback if no recipes of a type exist (avoid crash)
    // Ideally we might want some default "placeholder" recipes, but for now we handle nulls.

    // Helper to pick random recipe
    const pickRandom = (list: Recipe[]) => {
        if (list.length === 0) return null;
        const index = Math.floor(Math.random() * list.length);
        return list[index];
    };

    // 3. Batch Logic
    const batchLunchRecipe = useBatchLunch ? pickRandom(lunchRecipes) : null;

    // 4. Generate Days
    const days: MealPlanDay[] = [];
    const dayNames = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'];

    // Start from the given start date (Week Start)
    for (let i = 0; i < 7; i++) {
        const currentDate = addDays(monday, i);

        const dateString = toLocalDateKey(currentDate);
        const dayName = dayNames[i]; // Assuming startDate is Monday, which is standard in our app

        const meals: MealPlanMeal[] = [];
        let dailyCals = 0;

        // -- Breakfast --
        const bf = pickRandom(breakfastRecipes);
        if (bf) {
            meals.push(mapRecipeToMeal(bf, 'breakfast'));
            dailyCals += bf.calories;
        }

        // -- Lunch --
        // Use batch recipe if available, otherwise random
        const lu = batchLunchRecipe || pickRandom(lunchRecipes);
        if (lu) {
            meals.push(mapRecipeToMeal(lu, 'lunch'));
            dailyCals += lu.calories;
        }

        // -- Dinner -- 
        // Try to pick something different from lunch if possible
        const di = pickRandom(dinnerRecipes);
        if (di) {
            meals.push(mapRecipeToMeal(di, 'dinner'));
            dailyCals += di.calories;
        }

        // -- Snack --
        // Simple logic: add a snack if we are under target by > 200 cals
        if (dailyTarget - dailyCals > 200) {
            const sn = pickRandom(snackRecipes);
            if (sn) {
                meals.push(mapRecipeToMeal(sn, 'snack'));
                dailyCals += sn.calories;
            }
        }

        days.push({
            date: dateString,
            dayName: dayName,
            totalCalories: dailyCals,
            meals: meals
        });
    }

    // Calculate Week End
    const endDate = addDays(monday, 6);

    return {
        // id: generated by firestore
        weekStart: toLocalDateKey(monday),
        weekEnd: toLocalDateKey(endDate),
        goal: settings?.goalWeight && settings.currentWeight
            ? (settings.goalWeight < settings.currentWeight ? 'Fat Loss' : 'Muscle Gain')
            : 'Maintenance',
        dailyTargets: {
            calories: dailyTarget,
            protein: proteinTarget,
            carbs: carbsTarget,
            fat: fatTarget
        },
        days: days,
        isAiGenerated: true
    };
}

/**
 * Creates an empty meal plan structure for manual planning.
 */
export function createEmptyPlan(
    startDate: Date = new Date(),
    settings: UserSettings | null
): MealPlan {
    // N1: a plan always starts on its week's Monday, whatever date is passed in.
    const monday = getStartOfWeek(startDate);
    const dailyTarget = settings?.dailyCalorieTarget || 2000;

    let proteinTarget, carbsTarget, fatTarget;

    if (settings?.macroMode === 'grams' && settings.macroTargets) {
        proteinTarget = settings.macroTargets.protein;
        carbsTarget = settings.macroTargets.carbs;
        fatTarget = settings.macroTargets.fat;
    } else {
        proteinTarget = Math.round((dailyTarget * (settings?.macroSplit?.protein || 30)) / 100 / 4);
        carbsTarget = Math.round((dailyTarget * (settings?.macroSplit?.carbs || 35)) / 100 / 4);
        fatTarget = Math.round((dailyTarget * (settings?.macroSplit?.fat || 35)) / 100 / 9);
    }

    const days: MealPlanDay[] = [];

    for (let i = 0; i < 7; i++) {
        const currentDate = addDays(monday, i);

        days.push({
            date: toLocalDateKey(currentDate),
            dayName: currentDate.toLocaleDateString('en-US', { weekday: 'long' }),
            totalCalories: 0,
            meals: []
        });
    }

    const endDate = addDays(monday, 6);

    return {
        weekStart: toLocalDateKey(monday),
        weekEnd: toLocalDateKey(endDate),
        goal: settings?.goalWeight && settings.currentWeight
            ? (settings.goalWeight < settings.currentWeight ? 'Fat Loss' : 'Muscle Gain')
            : 'Maintenance',
        dailyTargets: {
            calories: dailyTarget,
            protein: proteinTarget,
            carbs: carbsTarget,
            fat: fatTarget
        },
        days: days,
        isAiGenerated: false
    };
}



function mapRecipeToMeal(recipe: Recipe, type: 'breakfast' | 'lunch' | 'dinner' | 'snack' | 'smoothie'): MealPlanMeal {
    return {
        id: crypto.randomUUID(), // Unique ID for this specific meal instance
        recipeId: recipe.id,     // Reference to the original recipe
        name: recipe.title,
        type: type,
        calories: recipe.calories,
        protein: recipe.protein,
        carbs: recipe.carbs,
        fat: recipe.fat,
        imageUrl: recipe.imageUrl,
        tag: recipe.tags[0] || 'Healthy',
        isEaten: false
    };
}
